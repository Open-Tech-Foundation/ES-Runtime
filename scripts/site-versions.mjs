// Writes website/src/versions.js from the crates that produce the two binaries,
// so the site cannot claim a version the repo does not build.
//
// There are two, released independently: `esrun` carries the workspace version
// (crates/runtime-cli sets `version.workspace = true`), and `esdev` sets its own
// in crates/dev-cli. Both are read here rather than in otfw.config.js because a
// component that renders a version also ships to the browser, where there is no
// filesystem to read a Cargo.toml from — the same reason src/benchmarks.js is a
// generated module rather than a lookup.
//
// Run through `tsr versions`.
import workspace from "../Cargo.toml";
import devCli from "../crates/dev-cli/Cargo.toml";

const versions = {
  esrun: workspace.workspace.package.version,
  esdev: devCli.package.version,
};

for (const [bin, v] of Object.entries(versions)) {
  if (!/^\d+\.\d+\.\d+/.test(v ?? "")) throw new Error(`no version for ${bin}: ${v}`);
}

const out = new URL("../website/src/versions.js", import.meta.url);
await Bun.write(
  out,
  `// AUTO-GENERATED by scripts/site-versions.mjs from the crates' Cargo.toml.
// Do not edit by hand — regenerate with: tsr versions
export default ${JSON.stringify(versions, null, 2)};
`,
);

console.log(`esrun ${versions.esrun} · esdev ${versions.esdev} → website/src/versions.js`);
