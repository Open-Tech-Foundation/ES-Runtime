#!/usr/bin/env python3
"""Generates crates/http/src/hpack/tables.rs from the text of RFC 7541.

    scripts/gen-hpack-tables.py path/to/rfc7541.txt

The static table (Appendix A) and the Huffman code (Appendix B) are read from
the RFC rather than typed: one wrong entry silently corrupts headers. Every
Huffman row is checked against itself — its bit string, its hex code and its
stated length must agree — and the code must be a complete prefix code. The
RFC text is https://www.rfc-editor.org/rfc/rfc7541.txt.
"""
import re
import sys

text = open(sys.argv[1], encoding="utf-8").read()
a = text.index("Appendix A.  Static Table Definition")
b = text.index("Appendix B.  Huffman Code")
c = text.index("Appendix C.  Examples")

static = []
for m in re.finditer(r"^\s*\| (\d+)\s*\| (\S+)\s*\| ?(.*?)\s*\|\s*$", text[a:b], re.M):
    index, name, value = int(m.group(1)), m.group(2), m.group(3)
    assert index == len(static) + 1, (index, len(static))
    static.append((name, value))
assert len(static) == 61, len(static)

codes = []
row = re.compile(r"^\s*(?:'.' |EOS )?\(\s*(\d+)\)\s+((?:\|[01]+)+)\s+([0-9a-f]+)\s+\[\s*(\d+)\]\s*$", re.M)
for m in row.finditer(text[b:c]):
    sym, bits, hexcode, length = int(m.group(1)), m.group(2).replace("|", ""), int(m.group(3), 16), int(m.group(4))
    assert sym == len(codes), (sym, len(codes))
    assert len(bits) == length, (sym, bits, length)
    assert int(bits, 2) == hexcode, (sym, bits, hexcode)
    codes.append((hexcode, length))
assert len(codes) == 257, len(codes)
# A complete prefix code: Kraft sum exactly 1.
assert sum(2 ** (30 - n) for _, n in codes) == 2 ** 30
bitstrings = [format(code, f"0{n}b") for code, n in codes]
for i, x in enumerate(bitstrings):
    for j, y in enumerate(bitstrings):
        assert i == j or not y.startswith(x), (i, j)

out = []
out.append("//! HPACK's static table and Huffman code, generated by")
out.append("//! `scripts/gen-hpack-tables.py` from the text of RFC 7541 (Appendices A")
out.append("//! and B). Do not edit by hand: regenerate.")
out.append("")
out.append("/// The static table (RFC 7541 Appendix A); index 1 is `STATIC[0]`.")
out.append("pub(crate) const STATIC: [(&str, &str); 61] = [")
for name, value in static:
    out.append(f"    ({name!r}, {value!r}),".replace("'", '"'))
out.append("];")
out.append("")
out.append("/// The Huffman code (RFC 7541 Appendix B): `(code, bit length)` for each")
out.append("/// octet, then EOS at index 256.")
out.append("pub(crate) const HUFFMAN: [(u32, u8); 257] = [")
for sym, (code, n) in enumerate(codes):
    out.append(f"    (0x{code:x}, {n}),")
out.append("];")
open("crates/http/src/hpack/tables.rs", "w", encoding="utf-8").write("\n".join(out) + "\n")
print("static entries:", len(static), "huffman codes:", len(codes))

# ---- Appendix C.3–C.6: the request/response sequences, as test vectors ----
# Each example: the encoded bytes, the decoded header list, and the dynamic
# table afterwards. Examples in one section share a decoder (C.3.1 → C.3.3).
# C.5 and C.6 use a 256-byte table, as their text says.
lines = text[c:].splitlines()
def is_page_furniture(l):
    return l.startswith("Peon & Ruellan") or (l.startswith("RFC 7541") and "HPACK" in l) or l.startswith("\f")
lines = [l for l in lines if not is_page_furniture(l)]
vectors = []
i = 0
heading = re.compile(r"^C\.([3-6])\.(\d)\.  ")
while i < len(lines):
    m = heading.match(lines[i])
    if not m:
        i += 1
        continue
    section, n = m.group(0).strip().rstrip("."), None
    name = lines[i].split()[0].rstrip(".")
    j = i + 1
    while not lines[j].strip().startswith("Hex dump of encoded data:"):
        j += 1
    j += 1
    encoded = b""
    while j < len(lines) and (lines[j].strip() == "" and not encoded or "|" in lines[j]):
        if "|" in lines[j]:
            encoded += bytes.fromhex(lines[j].split("|")[0].replace(" ", ""))
        j += 1
    while "Dynamic Table (after decoding):" not in lines[j]:
        j += 1
    j += 1
    table = []
    table_size = None
    while table_size is None:
        l = lines[j].strip()
        tm = re.match(r"^\[\s*\d+\] \(s =\s*(\d+)\) ([^:]+|:[^:]+): (.*)$", l)
        if tm:
            stated, entry_name, entry_value = int(tm.group(1)), tm.group(2), tm.group(3)
            # A long entry wraps onto the next line at a space.
            while lines[j + 1].startswith("         ") and not lines[j + 1].strip().startswith("Table size:") and not lines[j + 1].strip().startswith("["):
                j += 1
                entry_value += " " + lines[j].strip()
            # Each entry's stated size checks its own reading (RFC 7541 §4.1).
            assert len(entry_name) + len(entry_value) + 32 == stated, (name, entry_name, entry_value, stated)
            table.append((entry_name, entry_value))
        sm = re.match(r"^Table size:\s*(\d+)$", l)
        if sm:
            table_size = int(sm.group(1))
        j += 1
    while "Decoded header list:" not in lines[j]:
        j += 1
    j += 1
    headers = []
    # The list is indented; the next heading, whatever it is, is not.
    while j < len(lines) and (not lines[j].strip() or lines[j].startswith("   ")):
        l = lines[j]
        if l.strip():
            hm = re.match(r"^   (:?[^:]+): ?(.*)$", l)
            assert hm, (name, l)
            headers.append((hm.group(1), hm.group(2)))
        j += 1
    vectors.append((name, 256 if name[2] in "56" else 4096, encoded, headers, table, table_size))
    i = j
assert len(vectors) == 12, [v[0] for v in vectors]
for v in vectors:
    assert sum(len(n) + len(x) + 32 for n, x in v[4]) == v[5], v[0]

def lit(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'
out = ["//! RFC 7541 Appendix C.3–C.6, generated by `scripts/gen-hpack-tables.py`",
       "//! from the RFC text: each example's encoded bytes, its decoded header list,",
       "//! and the dynamic table after it. Do not edit by hand: regenerate.", "",
       "pub(super) struct Vector {",
       "    pub(super) name: &'static str,",
       "    pub(super) max_table: usize,",
       "    pub(super) encoded: &'static [u8],",
       "    pub(super) headers: &'static [(&'static str, &'static str)],",
       "    pub(super) table: &'static [(&'static str, &'static str)],",
       "    pub(super) table_size: usize,",
       "}", "",
       "pub(super) const VECTORS: &[Vector] = &["]
for name, max_table, encoded, headers, table, size in vectors:
    out.append("    Vector {")
    out.append(f"        name: {lit(name)},")
    out.append(f"        max_table: {max_table},")
    out.append("        encoded: &[" + ", ".join(f"0x{b:02x}" for b in encoded) + "],")
    out.append("        headers: &[" + ", ".join(f"({lit(n)}, {lit(v)})" for n, v in headers) + "],")
    out.append("        table: &[" + ", ".join(f"({lit(n)}, {lit(v)})" for n, v in table) + "],")
    out.append(f"        table_size: {size},")
    out.append("    },")
out.append("];")
open("crates/http/src/hpack/rfc_vectors.rs", "w", encoding="utf-8").write("\n".join(out) + "\n")
print("appendix C vectors:", ", ".join(v[0] for v in vectors))
