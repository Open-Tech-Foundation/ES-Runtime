//! Bakes `esdev init`'s bare project into the binary.
//!
//! The templates `esdev create` writes are not here: they are a package of
//! their own, `@opentf/esdev-templates`, fetched and verified when a project
//! is created (DECISIONS D220), so a template can be fixed without an esdev
//! release. The bare project is not a template — it is what `init` writes
//! into an empty directory, and it moves with `init`'s own code.
//!
//! What is skipped is what a working copy can leave behind.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

/// Directories and files never part of the bare project.
const SKIPPED: &[&str] = &[
    "node_modules",
    "dist",
    "target",
    ".git",
    "bun.lock",
    "bun.lockb",
    "package-lock.json",
    "yarn.lock",
    "pnpm-lock.yaml",
    ".DS_Store",
];

fn main() {
    reserve_main_stack();
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let mut generated = String::from(
        "// Generated by build.rs.\n\
         pub type TemplateFile = (&'static str, &'static [u8]);\n",
    );

    // The bare project `esdev init` writes for a new directory: internal, and
    // deliberately not a template: `create`'s come from their own package.
    // Paths keep their `shared/` + language overlay prefixes; `init` merges
    // them.
    let bare = manifest.join("bare");
    println!("cargo:rerun-if-changed={}", bare.display());
    let mut bare_files = Vec::new();
    collect(&bare, &bare, &mut bare_files);
    bare_files.sort();
    generated.push_str(
        "/// The files `esdev init` scaffolds for a new project: shared files\n\
         /// plus one language overlay (`js/` or `ts/`).\n\
         pub static BARE_FILES: &[TemplateFile] = &[\n",
    );
    for (relative, absolute) in bare_files {
        println!("cargo:rerun-if-changed={}", absolute.display());
        writeln!(
            generated,
            "    ({relative:?}, include_bytes!({:?})),",
            absolute.display().to_string()
        )
        .expect("write");
    }
    generated.push_str("];\n");

    let out = PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR")).join("templates.rs");
    std::fs::write(&out, generated).expect("write templates.rs");
}

/// Every file under `dir`, as (path relative to the template root, absolute
/// path).
fn collect(root: &Path, dir: &Path, files: &mut Vec<(String, PathBuf)>) {
    let Ok(read) = std::fs::read_dir(dir) else {
        return;
    };
    for entry in read.flatten() {
        let path = entry.path();
        let name = entry.file_name().to_string_lossy().into_owned();
        if SKIPPED.contains(&name.as_str()) {
            continue;
        }
        if path.is_dir() {
            collect(root, &path, files);
            continue;
        }
        let Ok(relative) = path.strip_prefix(root) else {
            continue;
        };
        // Always `/`, whatever wrote it: this string is a path the scaffolder
        // joins onto a destination, and on Windows a backslash in it would be
        // part of a filename rather than a separator.
        let relative = relative
            .components()
            .map(|part| part.as_os_str().to_string_lossy())
            .collect::<Vec<_>>()
            .join("/");
        files.push((relative, path.clone()));
    }
}

/// Reserves 8 MiB of stack for the main thread on Windows (DECISIONS D189).
/// The JS thread is the main thread, and MSVC's default is 1 MiB: less than
/// V8's own JS limit leaves room for, so deep JS or a deep document in a
/// native codec would abort the process instead of raising an error. Linux and
/// macOS already give the main thread 8 MiB; Node reserves the same. It is
/// address space, not memory — pages are committed as the stack grows.
fn reserve_main_stack() {
    const STACK: u64 = 8 * 1024 * 1024;
    if std::env::var("CARGO_CFG_TARGET_OS").as_deref() != Ok("windows") {
        return;
    }
    match std::env::var("CARGO_CFG_TARGET_ENV").as_deref() {
        Ok("msvc") => println!("cargo::rustc-link-arg-bins=/STACK:{STACK}"),
        Ok("gnu") => println!("cargo::rustc-link-arg-bins=-Wl,--stack,{STACK}"),
        _ => {}
    }
}
