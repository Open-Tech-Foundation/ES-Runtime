    /// pnpm puts a package's deps as symlinked peers inside
    /// `.pnpm/<pkg>@<ver>/node_modules/`; resolving them requires realpath-ing the
    /// package to its real location so the dependency walk finds the peer (D25).
    #[cfg(unix)]
    #[tokio::test]
    async fn resolves_pnpm_symlinked_transitive_dep() {
        use std::os::unix::fs::symlink;
        let (loader, root) = temp_tree("pnpm");
        let nm = root.join("node_modules");
        let foo_real = nm.join(".pnpm/foo@1/node_modules/foo");
        let bar_real = nm.join(".pnpm/bar@2/node_modules/bar");
        write(
            foo_real.join("package.json"),
            r#"{ "type":"module", "main":"index.js" }"#,
        );
        write(
            foo_real.join("index.js"),
            "import { bar } from 'bar'; export const foo = 'F' + bar;",
        );
        write(
            bar_real.join("package.json"),
            r#"{ "type":"module", "main":"index.js" }"#,
        );
        write(bar_real.join("index.js"), "export const bar = 'B';");
        // foo's peer dep `bar`, symlinked inside foo's .pnpm node_modules.
        symlink(
            "../../bar@2/node_modules/bar",
            nm.join(".pnpm/foo@1/node_modules/bar"),
        )
        .unwrap();
        // top-level `node_modules/foo` symlink into the store.
        symlink(".pnpm/foo@1/node_modules/foo", nm.join("foo")).unwrap();

        // foo resolves to its REAL store path (realpath), not the symlink.
        let foo_id = loader.resolve("foo", "").await.unwrap();
        assert!(
            foo_id.contains("/.pnpm/foo@1/node_modules/foo/index.js"),
            "{foo_id}"
        );
        // bar, imported by foo, is found via the .pnpm peer symlink because foo's
        // referrer is now its real location.
        let bar_id = loader.resolve("bar", &foo_id).await.unwrap();
        assert!(
            bar_id.contains("/.pnpm/bar@2/node_modules/bar/index.js"),
            "{bar_id}"
        );
        std::fs::remove_dir_all(&root).ok();
    }

    /// The invariant `import.meta.resolve` rests on (D41): the synchronous
    /// answer is the asynchronous one, for every shape of specifier — including
    /// the failures, which must fail the same way.
    #[tokio::test]
    async fn sync_and_async_resolution_agree_on_every_specifier() {
        let (_, root) = temp_tree("parity");
        write(
            root.join("package.json"),
            r##"{
                "name": "app",
                "type": "module",
                "exports": { "./pub": "./src/pub.js" },
                "imports": { "#priv": "./src/priv.js", "#dep": "pkg" }
            }"##,
        );
        write(root.join("src/pub.js"), "export const p = 1;");
        write(root.join("src/priv.js"), "export const q = 1;");
        write(root.join("src/main.js"), "export const m = 1;");
        let pkg = root.join("node_modules/pkg");
        write(
            pkg.join("package.json"),
            r##"{ "type": "module", "exports": { ".": "./i.mjs", "./gone": null } }"##,
        );
        write(pkg.join("i.mjs"), "export const v = 1;");
        let loader = NodeModuleLoader::with_base_and_root(&root, &root).unwrap();
        let referrer = Url::from_file_path(root.join("src/main.js"))
            .unwrap()
            .to_string();

        for specifier in [
            "./pub.js",       // relative
            "pkg",            // bare, via exports
            "pkg/gone",       // withdrawn — an error, and the same error
            "app/pub",        // self-reference
            "#priv",          // private, a path
            "#dep",           // private, another package
            "#nope",          // undeclared private
            "missing-pkg",    // not installed
            "node:fs",        // rejected builtin
            "../outside.mjs", // escapes the root
        ] {
            let asynchronous = loader.resolve(specifier, &referrer).await;
            let synchronous = loader
                .resolve_sync(specifier, &referrer)
                .expect("this loader resolves synchronously");
            match (&asynchronous, &synchronous) {
                (Ok(a), Ok(b)) => assert_eq!(a, b, "{specifier}: different ids"),
                (Err(a), Err(b)) => {
                    assert_eq!(
                        a.to_string(),
                        b.to_string(),
                        "{specifier}: different errors"
                    )
                }
                _ => panic!("{specifier}: one path resolved and the other did not"),
            }
        }
        std::fs::remove_dir_all(&root).ok();
    }

